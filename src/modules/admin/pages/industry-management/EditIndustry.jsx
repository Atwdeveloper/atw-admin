"use client";

import { useState, useEffect } from "react";
import { motion } from "framer-motion";
import { useNavigate, useParams } from "@/lib/navigation";
import { Save, Image as ImageIcon, Trash2 } from "lucide-react";
import Swal from "sweetalert2";
import {
  containerVariants,
  itemVariants,
} from "../../../../common/utils/motionVariants";
import {
  ICON_TYPES,
  getIndustryAPI,
  removeIndustryImageAPI,
  updateIndustryAPI,
  uploadIndustryImageAPI,
  validateIcon,
} from "../../../../api/adminV1/masterdataAPI";
import { apiError } from "../../../../api/javaApi";
import { useAdminPermissions } from "../../../../common/hooks/useAdminPermissions";
import Loader from "../../../../common/components/Loader";
import Breadcrumb from "../../../../common/components/Breadcrumb";

const EditIndustry = () => {
  const { id } = useParams();
  const navigate = useNavigate();
  const [errors, setErrors] = useState({});
  const { hasPermission, loading: permissionsLoading } = useAdminPermissions();
  const [formData, setFormData] = useState({
    name: "",
    image: null,
  });
  // code is generated by the backend — shown read-only
  const [initial, setInitial] = useState({ name: "", code: "" });
  const [imagePreview, setImagePreview] = useState(null);
  const [existingImage, setExistingImage] = useState(null);
  const [removeImage, setRemoveImage] = useState(false);
  const [loading, setLoading] = useState(true);
  const [submitting, setSubmitting] = useState(false);

  useEffect(() => {
    const fetchIndustry = async () => {
      try {
        setLoading(true);
        const industry = await getIndustryAPI(id);
        setFormData({
          name: industry.name || "",
          image: null,
        });
        setInitial({ name: industry.name || "", code: industry.code || "" });

        // A short-lived signed URL — fine for this page view, never stored.
        if (industry.imageUrl) {
          setExistingImage(industry.imageUrl);
          setImagePreview(industry.imageUrl);
        }
      } catch (error) {
        Swal.fire({
          icon: "error",
          title: "Failed to load industry",
          text: apiError(error, "Something went wrong").message,
        });
        navigate("/admin/industries");
      } finally {
        setLoading(false);
      }
    };
    if (id) fetchIndustry();
  }, [id, navigate]);

  const handleChange = (e) => {
    const { name, value, files } = e.target;

    if (name === "image") {
      const file = files[0] || null;
      setFormData((prev) => ({ ...prev, image: file }));
      setImagePreview(file ? URL.createObjectURL(file) : removeImage ? null : existingImage);
      setErrors((prev) => ({ ...prev, image: validateIcon(file) || "" }));
      if (file) setRemoveImage(false);
      return;
    }

    setFormData((prev) => ({
      ...prev,
      [name]: value,
    }));

    if (name === "name") {
      if (value && !/^[a-zA-Z0-9\s]+$/.test(value)) {
        setErrors((prev) => ({
          ...prev,
          name: "Special characters are not allowed",
        }));
      } else {
        setErrors((prev) => ({
          ...prev,
          name: "",
        }));
      }
    } else {
      setErrors((prev) => ({ ...prev, [name]: "" }));
    }
  };

  const handleRemoveImage = () => {
    setRemoveImage(true);
    setFormData((prev) => ({ ...prev, image: null }));
    setImagePreview(null);
    setErrors((prev) => ({ ...prev, image: "" }));
  };

  const validate = () => {
    const newErrors = {};
    const name = formData.name.trim();

    if (!name) newErrors.name = "Industry name is required";
    else if (!/^[a-zA-Z0-9\s]+$/.test(name)) newErrors.name = "Special characters are not allowed";
    else if (name.length > 150) newErrors.name = "Industry name must be at most 150 characters";

    const imageError = validateIcon(formData.image);
    if (imageError) newErrors.image = imageError;

    setErrors(newErrors);
    return Object.keys(newErrors).length === 0;
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (submitting || !validate()) return;

    const name = formData.name.trim();
    setSubmitting(true);

    // 1. Name — only if it changed
    if (name !== initial.name) {
      try {
        await updateIndustryAPI(id, { name });
        setInitial((prev) => ({ ...prev, name }));
      } catch (error) {
        const { code: errCode, message, fieldErrors } = apiError(error, "Something went wrong");
        if (errCode === "CONFLICT") {
          // Only the name is unique-checked now (the code is server-generated)
          setErrors((prev) => ({ ...prev, name: message }));
        } else if (Object.keys(fieldErrors).length) {
          setErrors((prev) => ({ ...prev, ...fieldErrors }));
        }
        Swal.fire({
          icon: "error",
          title: "Failed to update industry",
          text: message,
        });
        setSubmitting(false);
        return;
      }
    }

    // 2. Icon — a separate upload/remove call
    try {
      if (formData.image) {
        await uploadIndustryImageAPI(id, formData.image);
      } else if (removeImage && existingImage) {
        await removeIndustryImageAPI(id);
      }
    } catch (error) {
      setSubmitting(false);
      Swal.fire({
        icon: "warning",
        title: "Industry saved, image not updated",
        text: apiError(error, "The image couldn't be updated.").message,
      });
      return;
    }

    setSubmitting(false);
    Swal.fire({
      icon: "success",
      title: "Success!",
      text: "Industry updated successfully",
      timer: 1500,
      showConfirmButton: false,
    });
    navigate("/admin/industries");
  };

  if (permissionsLoading || loading) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center">
        <Loader />
      </div>
    );
  }

  if (!hasPermission("industry", "edit")) {
    return (
      <div className="flex-1 bg-gray-50 p-4 flex items-center justify-center">
        <div className="bg-white rounded-lg p-8 text-center max-w-md">
          <h2 className="text-2xl font-bold text-gray-800 mb-2">
            Access Denied
          </h2>
          <p className="text-gray-600 mb-6">
            You don't have permission to edit industries.
          </p>
          <button
            onClick={() => navigate("/admin/industries")}
            className="px-6 py-2 bg-blue-600 text-white rounded-lg hover:bg-blue-700"
          >
            Go Back
          </button>
        </div>
      </div>
    );
  }

  return (
    <motion.div
      className="flex-1 bg-gray-50 p-4"
      initial="hidden"
      animate="visible"
      variants={containerVariants}
    >
      <motion.div className="p-4 pb-0">
        <Breadcrumb
          items={[
            { label: "Industries", path: "/admin/industries" },
            { label: initial.name || "Industry" },
          ]}
        />
      </motion.div>
      <motion.div className="" variants={itemVariants}>
        <div className="flex items-center gap-4 mb-6">
          <h1 className="text-2xl font-bold text-gray-800">Edit Industry</h1>
        </div>

        <form
          onSubmit={handleSubmit}
          className="space-y-6 max-w-2xl bg-white rounded-2xl border border-gray-200 shadow-sm p-6"
        >
          <div>
            <label
              htmlFor="name"
              className="block text-sm font-medium text-gray-700 mb-2"
            >
              Industry Name <span className="text-red-500">*</span>
            </label>
            <input
              type="text"
              id="name"
              name="name"
              value={formData.name}
              onChange={handleChange}
              maxLength={150}
              placeholder="Enter industry name"
              className={`w-full px-4 py-2 border rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-blue-500 ${
                errors.name ? "border-red-500" : "border-gray-300"
              }`}
              autoFocus
            />
            {errors.name && (
              <p className="mt-1 text-sm text-red-600">{errors.name}</p>
            )}
          </div>

          {initial.code && (
            <div>
              <label htmlFor="code" className="block text-sm font-medium text-gray-700 mb-2">
                Industry Code
              </label>
              <input
                type="text"
                id="code"
                value={initial.code}
                readOnly
                disabled
                className="w-full px-4 py-2 border border-gray-200 rounded-lg bg-gray-50 text-gray-500 cursor-not-allowed"
              />
              <p className="text-xs text-gray-400 mt-1">Generated automatically.</p>
            </div>
          )}

          <div>
            <label
              htmlFor="image"
              className="block text-sm font-medium text-gray-700 mb-2"
            >
              Industry Image
            </label>
            <div className="flex items-center gap-4">
              <div className="w-16 h-16 rounded-lg overflow-hidden bg-gray-100 border border-gray-200 flex items-center justify-center flex-shrink-0">
                {imagePreview ? (
                  <img
                    src={imagePreview}
                    className="w-full h-full object-cover"
                    alt="Industry preview"
                  />
                ) : (
                  <ImageIcon className="w-6 h-6 text-gray-400" />
                )}
              </div>
              <input
                type="file"
                id="image"
                name="image"
                accept={ICON_TYPES.join(",")}
                onChange={handleChange}
                className="w-full text-sm text-gray-600 file:mr-4 file:py-2 file:px-4 file:rounded-lg file:border-0 file:text-sm file:font-medium file:bg-blue-50 file:text-blue-700 hover:file:bg-blue-100"
              />
              {existingImage && !removeImage && !formData.image && (
                <button
                  type="button"
                  onClick={handleRemoveImage}
                  className="flex items-center gap-1 px-3 py-2 text-sm text-red-600 border border-red-200 rounded-lg hover:bg-red-50 whitespace-nowrap"
                >
                  <Trash2 className="w-4 h-4" />
                  Remove
                </button>
              )}
            </div>
            {errors.image ? (
              <p className="mt-1 text-sm text-red-600">{errors.image}</p>
            ) : (
              <p className="text-xs text-gray-400 mt-1">
                {removeImage
                  ? "The current image will be removed when you save."
                  : "PNG, JPEG or WEBP, up to 2MB. Leave empty to keep the current image."}
              </p>
            )}
          </div>

          <div className="flex justify-end gap-3">
            <button
              type="button"
              onClick={() => navigate("/admin/industries")}
              className="px-6 py-2 border border-gray-300 rounded-lg text-gray-700 hover:bg-gray-50"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={submitting}
              className="flex items-center gap-2 px-6 py-2 bg-blue-600 text-white rounded-lg hover:bg-blue-700 disabled:bg-blue-300"
            >
              {submitting ? (
                <>
                  <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin"></div>
                  Updating...
                </>
              ) : (
                <>
                  <Save className="w-4 h-4" />
                  Update Industry
                </>
              )}
            </button>
          </div>
        </form>
      </motion.div>
    </motion.div>
  );
};

export default EditIndustry;
