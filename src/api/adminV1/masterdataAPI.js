import javaApi, { unwrap } from "../javaApi";
import { invalidateMasterdataThumb } from "../../common/components/MasterdataThumb";

// Java masterdata endpoints (/admin/masterdata/**). Conventions shared by every
// resource here:
// - status is "ACTIVE" | "INACTIVE", set with an explicit target (no toggle).
// - Every list endpoint is paged: -> { content, page, size, totalElements,
//   totalPages, first, last }. page is 0-based; default size 100, max 500.
//   Filters are repeated params (?statuses=A&statuses=B), plus free-text
//   `search` (name substring) where the entity has a name.
//   `sort` is "field,dir"; allowed fields are name/status/createdAt
//   (minimum wage: effectiveFrom/minDailyRate/status/createdAt). An
//   unsupported sort field is a 400.
// - Delete is a real, hard delete guarded by foreign keys (409 CONFLICT with a
//   friendly message when still referenced). Every entity has it except
//   minimum wage rates (append-only history — deactivate instead).
// - Bulk endpoints process each id independently:
//   -> { successCount, failures: [{ id, reason }] }.
// - Industry and skill-category `code` is generated by the backend (IND0000001 /
//   SKC0000001) — never sent on create/update.
// - Icons (industries, designations, skills) are uploaded separately as
//   multipart field "file": PNG/JPEG/WEBP only, max 2MB. List responses always
//   have imageUrl: null; the single-item GET returns a ~15 min signed URL.

const BASE = "/admin/masterdata";

// Spring binds repeated params (statuses=A&statuses=B), not axios' default statuses[]=A.
const repeatParams = { indexes: null };

// Drops empty values so they aren't sent as filters.
const clean = (params = {}) =>
  Object.fromEntries(
    Object.entries(params).filter(
      ([, v]) => v !== undefined && v !== null && v !== "" && !(Array.isArray(v) && v.length === 0),
    ),
  );

const getPage = (path) => (params = {}) =>
  javaApi.get(`${BASE}/${path}`, { params: clean(params), paramsSerializer: repeatParams }).then(unwrap);

// Whole list as a plain array, for dropdowns (one page at the max size).
const ALL = { page: 0, size: 500 };
const contentOf = (page) => page?.content || [];

const setStatus = (path) => (id, status) =>
  javaApi.post(`${BASE}/${path}/${id}/status`, { status }).then(unwrap);

const bulkStatus = (path) => (ids, status) =>
  javaApi.post(`${BASE}/${path}/bulk-status`, { ids, status }).then(unwrap);

const remove = (path) => (id) => javaApi.delete(`${BASE}/${path}/${id}`).then(unwrap);

const bulkDelete = (path) => (ids) => javaApi.post(`${BASE}/${path}/bulk-delete`, { ids }).then(unwrap);

const uploadImage = (path) => (id, file) => {
  const body = new FormData();
  body.append("file", file);
  return javaApi
    .put(`${BASE}/${path}/${id}/image`, body, { headers: { "Content-Type": "multipart/form-data" } })
    .then(unwrap)
    .finally(() => invalidateMasterdataThumb(path, id));
};

const removeImage = (path) => (id) =>
  javaApi
    .delete(`${BASE}/${path}/${id}/image`)
    .then(unwrap)
    .finally(() => invalidateMasterdataThumb(path, id));

export const ICON_TYPES = ["image/png", "image/jpeg", "image/webp"];
export const ICON_MAX_BYTES = 2 * 1024 * 1024;

// Client-side check matching the backend's icon rules. Returns an error message or null.
export const validateIcon = (file) => {
  if (!file) return null;
  if (!ICON_TYPES.includes(file.type)) return "Icon must be a PNG, JPEG or WEBP image";
  if (file.size > ICON_MAX_BYTES) return "Icon must be 2MB or smaller";
  return null;
};

